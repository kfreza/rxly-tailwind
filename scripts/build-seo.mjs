// Generate src/partials/head-meta.html (meta, Open Graph, JSON-LD) from src/i18n/en.json.
// Keeps the FAQPage structured data identical to the visible FAQ copy.
// Usage: node scripts/build-seo.mjs   (run after scripts/extract-i18n.mjs)
import { readFileSync, writeFileSync } from 'node:fs';

const en = JSON.parse(readFileSync('src/i18n/en.json', 'utf8'));
const SITE = 'https://rxly.net/';
const title = 'Rxly — Clinic & chamber software for Bangladesh';
const description = en['hero.lead'];
const esc = (s) => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');

const faqKeys = ['serial', 'buy', 'bangla', 'texts', 'video', 'pay', 'leave'];
const plans = [
  ['Solo', en['pricing.solo_desc'], 1000],
  ['Clinic', en['pricing.clinic_desc'], 2500],
  ['Hospital', en['pricing.hospital_desc'], 5000],
];

const graph = {
  '@context': 'https://schema.org',
  '@graph': [
    {
      '@type': 'Organization',
      '@id': `${SITE}#org`,
      name: 'Rxly',
      url: SITE,
      logo: `${SITE}images/logo.svg`,
      areaServed: 'BD',
    },
    {
      '@type': 'WebSite',
      '@id': `${SITE}#website`,
      url: SITE,
      name: 'Rxly',
      inLanguage: ['en', 'bn'],
      publisher: { '@id': `${SITE}#org` },
    },
    {
      '@type': 'SoftwareApplication',
      name: 'Rxly',
      url: SITE,
      applicationCategory: 'BusinessApplication',
      applicationSubCategory: 'Medical practice management',
      operatingSystem: 'Web browser',
      description,
      inLanguage: ['en', 'bn'],
      publisher: { '@id': `${SITE}#org` },
      offers: plans.map(([name, desc, price]) => ({
        '@type': 'Offer',
        name,
        description: desc,
        price: String(price),
        priceCurrency: 'BDT',
        category: 'subscription',
        url: `${SITE}#pricing`,
      })),
    },
    {
      '@type': 'FAQPage',
      mainEntity: faqKeys.map((k) => ({
        '@type': 'Question',
        name: en[`faq.${k}_q`],
        acceptedAnswer: { '@type': 'Answer', text: en[`faq.${k}_a`] },
      })),
    },
  ],
};

const html = `<!-- AUTO-GENERATED by scripts/build-seo.mjs — edit the script, not this file. -->
<title>${esc(title)}</title>
<meta name="description" content="${esc(description)}" />
<link rel="canonical" href="${SITE}" />
<meta name="theme-color" content="#066afe" />
<meta property="og:type" content="website" />
<meta property="og:site_name" content="Rxly" />
<meta property="og:url" content="${SITE}" />
<meta property="og:title" content="${esc(title)}" />
<meta property="og:description" content="${esc(description)}" />
<meta property="og:image" content="${SITE}og-image.png" />
<meta property="og:image:width" content="1200" />
<meta property="og:image:height" content="630" />
<meta property="og:locale" content="en_US" />
<meta property="og:locale:alternate" content="bn_BD" />
<meta name="twitter:card" content="summary_large_image" />
<meta name="twitter:title" content="${esc(title)}" />
<meta name="twitter:description" content="${esc(description)}" />
<meta name="twitter:image" content="${SITE}og-image.png" />
<link rel="apple-touch-icon" href="/apple-touch-icon.png" />
<link rel="preload" as="image" href="/images/hero/desk.webp" imagesrcset="/images/hero/desk-800.webp 800w, /images/hero/desk-1200.webp 1200w, /images/hero/desk.webp 2160w" imagesizes="(min-width: 1276px) 1174px, calc(100vw - 48px)" fetchpriority="high" />
<script type="application/ld+json">${JSON.stringify(graph)}</script>
`;
writeFileSync('src/partials/head-meta.html', html);
console.log(`head-meta.html written (${faqKeys.length} FAQ items, ${plans.length} offers)`);
